import enum
import uuid

from sqlalchemy import BigInteger, CheckConstraint, Enum, ForeignKey, String, Uuid
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base
from app.db.mixins import TimestampMixin, UUIDPrimaryKeyMixin


class FileCategory(enum.StrEnum):
    doctor_photo = "doctor_photo"
    patient_photo = "patient_photo"
    patient_document = "patient_document"
    doctor_credential = "doctor_credential"


class FileStatus(enum.StrEnum):
    active = "active"
    # Nothing references it any more, but deleting the R2 object failed:
    # scripts/reconcile_storage.py retries.
    pending_deletion = "pending_deletion"
    deleted = "deleted"


class StoredFile(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """One object in R2. Bytes live in R2; this row is the metadata.

    Ownership is not stored here: the owning row points at the file
    (doctors.photo_file_id, patients.photo_file_id, patient_documents.file_id,
    doctor_application_documents.file_id),
    and authorization follows that owner. URLs are never stored: they are
    signed when a response needs one.
    """

    __tablename__ = "stored_files"
    __table_args__ = (CheckConstraint("size_bytes > 0", name="size_positive"),)

    bucket: Mapped[str] = mapped_column(String(63))
    # Generated by the server from ids only (file_service.object_key).
    object_key: Mapped[str] = mapped_column(String(512), unique=True)
    category: Mapped[FileCategory] = mapped_column(
        Enum(FileCategory, name="file_category", values_callable=lambda e: [m.value for m in e]), index=True
    )
    # Detected from the bytes, never taken from the browser.
    content_type: Mapped[str] = mapped_column(String(100))
    size_bytes: Mapped[int] = mapped_column(BigInteger)
    sha256: Mapped[str] = mapped_column(String(64))
    # As the uploader named it. Can contain PHI ("ali_hiv_test.pdf"): never log it.
    original_filename: Mapped[str | None] = mapped_column(String(255))
    uploaded_by_user_id: Mapped[uuid.UUID | None] = mapped_column(
        Uuid, ForeignKey("users.id", ondelete="SET NULL")
    )
    status: Mapped[FileStatus] = mapped_column(
        Enum(FileStatus, name="file_status", values_callable=lambda e: [m.value for m in e]),
        default=FileStatus.active,
        index=True,
    )
