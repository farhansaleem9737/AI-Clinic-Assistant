import { useState } from "react";
import { getErrorMessage } from "../../services/api";
import { registerPatient } from "../../services/patientService";
import { EMPTY_PATIENT, patientPayload, SEX_LABELS, SEX_OPTIONS } from "../../utils/patient";
import { EMAIL_PATTERN, todayIso } from "../../utils/validation";
import ConfirmDialog from "../ConfirmDialog";

function validate(form) {
  const errors = {};
  if (!form.first_name.trim()) errors.first_name = "Enter the first name.";
  if (!form.last_name.trim()) errors.last_name = "Enter the last name.";
  if (!form.date_of_birth) errors.date_of_birth = "Enter the date of birth.";
  else if (form.date_of_birth > todayIso()) errors.date_of_birth = "The date of birth cannot be in the future.";
  else if (form.date_of_birth < "1900-01-01") errors.date_of_birth = "Enter a valid date of birth.";
  if (form.email.trim() && !EMAIL_PATTERN.test(form.email.trim())) errors.email = "Enter a valid email address.";
  return errors;
}

// The API's 422 details -> { field: message } for this form.
function serverErrors(err) {
  const fields = {};
  for (const item of err?.response?.data?.error?.details?.errors ?? []) {
    const field = item.loc?.at(-1);
    if (field in EMPTY_PATIENT) fields[field] = "Check this value.";
  }
  return fields;
}

function Field({ id, label, error, children }) {
  return (
    <div className="edit-field">
      <label htmlFor={id}>{label}</label>
      {children}
      {error && (
        <small className="field-error" id={`${id}-error`}>
          {error}
        </small>
      )}
    </div>
  );
}

/**
 * Register a walk-in patient: a patient record without a portal login (no
 * password is invented). The MRN is generated by the database. A login can
 * be created later from the patient's record.
 */
export default function AddPatientDialog({ onCreated, onClose }) {
  const [form, setForm] = useState(EMPTY_PATIENT);
  const [errors, setErrors] = useState({});
  const [error, setError] = useState("");
  const [busy, setBusy] = useState(false);
  const bind = (field) => ({
    id: `new-patient-${field}`,
    value: form[field] ?? "",
    onChange: (e) => {
      setForm({ ...form, [field]: e.target.value });
      setErrors({ ...errors, [field]: undefined });
    },
    "aria-invalid": errors[field] ? true : undefined,
    "aria-describedby": errors[field] ? `new-patient-${field}-error` : undefined,
    disabled: busy,
  });

  const save = async () => {
    const found = validate(form);
    setErrors(found);
    setError("");
    if (Object.keys(found).length) return;
    setBusy(true);
    try {
      const trimmed = Object.fromEntries(Object.entries(form).map(([k, v]) => [k, typeof v === "string" ? v.trim() : v]));
      const res = await registerPatient(patientPayload(trimmed));
      onCreated(res.data);
    } catch (err) {
      setErrors(serverErrors(err));
      setError(getErrorMessage(err, "Could not register the patient"));
      setBusy(false);
    }
  };

  return (
    <ConfirmDialog
      title="Add Patient"
      confirmLabel="Register patient"
      busy={busy}
      error={error}
      onConfirm={save}
      onCancel={onClose}
      className="wide-dialog"
    >
      <div className="edit-grid">
        <Field id="new-patient-first_name" label="First name" error={errors.first_name}>
          <input maxLength={100} autoComplete="off" required {...bind("first_name")} />
        </Field>
        <Field id="new-patient-last_name" label="Last name" error={errors.last_name}>
          <input maxLength={100} autoComplete="off" required {...bind("last_name")} />
        </Field>
        <Field id="new-patient-date_of_birth" label="Date of birth" error={errors.date_of_birth}>
          <input type="date" min="1900-01-01" max={todayIso()} required {...bind("date_of_birth")} />
        </Field>
        <Field id="new-patient-sex_at_birth" label="Gender" error={errors.sex_at_birth}>
          <select {...bind("sex_at_birth")}>
            {SEX_OPTIONS.map((s) => (
              <option key={s} value={s}>
                {SEX_LABELS[s]}
              </option>
            ))}
          </select>
        </Field>
        <Field id="new-patient-phone" label="Phone (optional)" error={errors.phone}>
          <input type="tel" maxLength={30} autoComplete="off" {...bind("phone")} />
        </Field>
        <Field id="new-patient-email" label="Email (optional)" error={errors.email}>
          <input type="email" autoComplete="off" {...bind("email")} />
        </Field>
        <Field id="new-patient-address" label="Address (optional)" error={errors.address}>
          <input maxLength={500} autoComplete="off" {...bind("address")} />
        </Field>
        <Field id="new-patient-preferred_language" label="Preferred language (optional)" error={errors.preferred_language}>
          <input maxLength={35} {...bind("preferred_language")} />
        </Field>
      </div>
      <p className="muted small">
        The medical record number is assigned automatically. No portal login is created; one can be set up later from
        the patient&apos;s record.
      </p>
    </ConfirmDialog>
  );
}
